#!/usr/bin/env bash
# Install the privileged URnetwork launcher.
#
# The previous version of this script granted NOPASSWD on the launcher inside
# the git checkout, on build/urnetwork-vpn and on /usr/sbin/ip.  Everything it
# authorised was writable by the same user, so the sudo rule was equivalent to
# passwordless root: any process running as that user could take over the
# machine.  This installer instead copies the launcher and the built binaries
# to a root-owned directory first, and whitelists only that copy.
set -euo pipefail

if [[ ${EUID} -ne 0 ]]; then
    exec sudo "$0" "$@"
fi

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SRC_DIR/.." && pwd)"
TARGET_USER="${SUDO_USER:-}"

if [[ -z "$TARGET_USER" || "$TARGET_USER" == "root" ]]; then
    echo "error: run this script as a normal user, e.g. sudo $0" >&2
    exit 1
fi

DEST_DIR="/usr/local/libexec/urnetwork"
DEST="$DEST_DIR/urnetwork-connect.sh"
# The root-owned copy computes BUILD_DIR as <script dir>/../build, so the
# binaries have to live in /usr/local/libexec/build next to it.
BIN_DEST="/usr/local/libexec/build"
SUDOERS_FILE="/etc/sudoers.d/urnetwork"

install -d -m 0755 "$DEST_DIR" "$BIN_DEST"
install -m 0755 -o root -g root "$SRC_DIR/urnetwork-connect.sh" "$DEST"
# The askpass helper runs as the invoking user (sudo execs it before switching
# to root), but a root-owned copy is more durable than a path in the checkout.
install -m 0755 -o root -g root "$SRC_DIR/urnetwork-askpass.sh" "$DEST_DIR/urnetwork-askpass.sh"
# The credentials helper reads/writes the system secret store; installing a
# root-owned copy keeps it available if the checkout is moved or deleted.
install -m 0755 -o root -g root "$SRC_DIR/urnetwork-credentials.py" "$DEST_DIR/urnetwork-credentials.py"

missing=0
for bin in socksproxy urnetwork-vpn; do
    if [[ -x "$ROOT_DIR/build/$bin" ]]; then
        install -m 0755 -o root -g root "$ROOT_DIR/build/$bin" "$BIN_DEST/$bin"
    else
        echo "warning: $ROOT_DIR/build/$bin is missing (run: make build)" >&2
        missing=1
    fi
done

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

cat > "$tmp" <<EOF
# Generated by $SRC_DIR/install-nopasswd.sh -- do not edit manually.
#
# Only the root-owned copy of the launcher is authorised.  The git checkout
# and the binaries in build/ are intentionally NOT sudo-whitelisted: they are
# writable by the invoking user, so trusting them here would be passwordless
# root.  Re-run the installer after rebuilding or editing the launcher.
#
# No credentials or paths are kept from the caller's environment: the launcher
# forwards the account via a 0600 credentials file and the engine derives its
# state file from SUDO_UID, so URNETWORK_STATE_FILE/URNETWORK_CONFIG_DIR cannot
# be used to make the root engine write or delete an arbitrary file.
Defaults!$DEST env_keep += "URNETWORK_VERBOSE"
$TARGET_USER ALL=(root) NOPASSWD: $DEST
EOF

visudo -cf "$tmp" >/dev/null
install -m 0440 -o root -g root "$tmp" "$SUDOERS_FILE"

echo
echo "Installed:"
echo "  launcher: $DEST"
echo "  askpass:  $DEST_DIR/urnetwork-askpass.sh"
echo "  secrets:  $DEST_DIR/urnetwork-credentials.py"
echo "  binaries: $BIN_DEST/{socksproxy,urnetwork-vpn}"
echo "  sudoers:  $SUDOERS_FILE"
echo
echo "  $TARGET_USER may run the launcher with sudo without a password."
echo "  Re-run this installer after 'make build' or after editing the launcher."

if [[ $missing -ne 0 ]]; then
    exit 1
fi
